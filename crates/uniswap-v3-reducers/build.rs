//! Stages the Uniswap V3 overlay sources into `OUT_DIR`.
//!
//! The overlay reducers and their test harnesses are written against the
//! directory layout that `scripts/materialize-uniswap-v3-*.sh` build: reducer
//! sources and generated bindings in `src/`, pinned contract documents in a
//! sibling `configs/`, harnesses in `tests/`. They reach across it with
//! relative `include_str!("../configs/…")`, `include!("../src/…")` and
//! `#[path = "../src/…"]`, so they cannot be compiled where they are checked
//! in: `uniswap-v3/position-reducer/` has no `configs/` directory, and
//! `uniswap-v3/npm-observation-plan/src/` has no `npm_handler_reducer.rs`.
//!
//! This build script performs exactly the copies those scripts perform, into
//! `OUT_DIR` instead of a temporary tree. The overlay files stay the single
//! source of truth, so every SHA-256 the overlay sources, `contract-v1.json`
//! documents, and verifiers pin remains authoritative.
//!
//! One staged byte differs from the overlay, and only in a comment: a test
//! harness is a crate root that this crate reaches with `include!`, and rustc
//! rejects an inner doc comment that arrives through a macro expansion
//! (E0753). `Staging::HarnessRoot` therefore rewrites the leading `//!` block
//! of a harness to `//`. `tests/staging.rs` asserts that is the only
//! difference. Reducer sources keep their inner doc comments because they are
//! declared as out-of-line modules, not included.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

include!("overlay_manifest.rs");

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=overlay_manifest.rs");
    let overlay_root = Path::new(OVERLAY_ROOT);
    let staging =
        PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo")).join("overlay");

    for (staged, overlay, mode) in STAGED {
        let source = overlay_root.join(overlay);
        println!("cargo:rerun-if-changed={}", source.display());
        let bytes = fs::read(&source)
            .unwrap_or_else(|error| panic!("cannot read {}: {error}", source.display()));
        write_if_changed(&staging.join(staged), &stage(&bytes, *mode));
    }

    write_if_changed(
        &staging.join("src/reducers.rs"),
        reducer_modules().as_bytes(),
    );
}

/// Renders the generated module list the library includes.
///
/// Every module carries `clippy::unnecessary_map_or`: the overlay sources are
/// linted and formatted against the pinned 1.79.0 toolchain, and that lint
/// postdates it. Allowing it here keeps the workspace clippy gate strict
/// without editing a pinned source.
fn reducer_modules() -> String {
    let mut rendered = String::from(
        "// @generated by build.rs. Declares the staged overlay reducers as out-of-line\n\
         // modules so each source keeps its own inner doc comment.\n",
    );
    for (module, doc, allows) in REDUCER_MODULES {
        rendered.push_str(&format!("\n/// {doc}\n"));
        rendered.push_str("#[allow(clippy::unnecessary_map_or)]\n");
        for allow in *allows {
            rendered.push_str(&format!("#[allow({allow})]\n"));
        }
        rendered.push_str(&format!(
            "#[cfg(not(target_arch = \"wasm32\"))]\n#[path = \"{module}.rs\"]\npub mod {module};\n"
        ));
    }
    rendered
}

fn write_if_changed(destination: &Path, bytes: &[u8]) {
    let parent = destination
        .parent()
        .expect("staged paths always have a parent");
    fs::create_dir_all(parent)
        .unwrap_or_else(|error| panic!("cannot create {}: {error}", parent.display()));
    if fs::read(destination).is_ok_and(|existing| existing == bytes) {
        return;
    }
    fs::write(destination, bytes)
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", destination.display()));
}
