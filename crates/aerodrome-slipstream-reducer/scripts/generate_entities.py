#!/usr/bin/env python3
"""Generate typed declarations from the locked schema; tests use a separate parser."""

import hashlib
import pathlib
import re

CRATE = pathlib.Path(__file__).resolve().parent.parent
SCHEMA_SHA256 = "09d7c40167fc27c3aa2de0ec003fe7b0b469e132943cc26dcd4db6064769d0e8"
schema = (CRATE / "../../aerodrome-slipstream-base/reference/schema.graphql").read_text()
if hashlib.sha256(schema.encode()).hexdigest() != SCHEMA_SHA256:
    raise SystemExit("locked Aerodrome schema changed; review types before regenerating")
schema = re.sub(r"#[^\n]*", "", schema)
classes = {
    "Factory": "Hot",
    "Bundle": "Hot",
    "Token": "Hot",
    "Pool": "Hot",
    "Tick": "Tiered",
    "Position": "Tiered",
    "Collect": "NeverWritten",
    "Flash": "NeverWritten",
    "TickHourData": "NeverWritten",
}
scalar_types = {
    "Int": "i32",
    "BigInt": "BigInt",
    "BigDecimal": "GraphDecimal",
    "Bytes": "Vec<u8>",
    "[Pool!]": "Vec<String>",
}
entries = []
output = [
    "// Generated by scripts/generate_entities.py from the locked schema.",
    "use super::*;",
]
for name, body in sorted(re.findall(r"type\s+(\w+)\s+@entity[^\{]*\{(.*?)\}", schema, re.S)):
    fields = []
    for line in body.splitlines():
        match = re.match(r"\s*(\w+)\s*:\s*([\[\]!\w]+)", line)
        if not match or "@derivedFrom" in line:
            continue
        field, graphql_type = match.groups()
        rust_type = scalar_types.get(graphql_type.rstrip("!"), "String")
        if not graphql_type.endswith("!"):
            rust_type = f"Presence<{rust_type}>"
        rust_name = re.sub(
            r"([a-z0-9])([A-Z])",
            r"\1_\2",
            re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", field),
        ).lower()
        fields.append((field, f'    {rust_name}: {rust_type} => "{field}": "{graphql_type}",'))
    default_class = (
        "PeriodDay" if name.endswith("DayData")
        else "PeriodHour" if name.endswith("HourData")
        else "BlockLocal"
    )
    entity_class = classes.get(name, default_class)
    entries.append(name)
    output.append(
        f"graph_entity! {{ {name}, {entity_class}, {{\n"
        + "\n".join(value for _, value in sorted(fields))
        + "\n} }"
    )
output.append(
    "pub const ALL_ENTITIES: &[EntityDef] = &["
    + ",".join(name + "::DEF" for name in entries)
    + "];"
)
(CRATE / "src/entity/types.rs").write_text("\n\n".join(output) + "\n")
